test("preserves the Rust registration ceremony including credential protection extensions", async () => {
  const body = { challenge: "fixture-registration", public_key: registrationOptions };
  const client = new SwarmieClient({
    fetch: async (input) =>
      Response.json(
        requestUrl(input) === "/api/me" ? { user: userFixture, csrf_token: "fixture" } : body,
      ),
  });
  const result = await Effect.runPromise(client.passkeyRegistrationOptions("Device"));
  expect(result).toEqual(body);
});

test("does not cache CSRF from a malformed identity before a later protected command", async () => {
  let sessionReads = 0;
  const tokens: (string | null)[] = [];
  const client = new SwarmieClient({
    fetch: async (input, init) => {
      if (requestUrl(input) === "/api/me") {
        sessionReads += 1;
        return Response.json(
          sessionReads === 1
            ? { user: {}, csrf_token: "untrusted" }
            : { user: userFixture, csrf_token: "validated" },
        );
      }
      tokens.push(new Headers(init?.headers).get("X-CSRF-Token"));
      return new Response(null, { status: 204 });
    },
  });
  const initial = await Effect.runPromise(Effect.either(client.me()));
  expect(Either.isLeft(initial)).toBe(true);
  await Effect.runPromise(client.leaveWorkspace("workspace"));
  expect(sessionReads).toBe(2);
  expect(tokens).toEqual(["validated"]);
});
