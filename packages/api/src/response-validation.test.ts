import { expect, test } from "bun:test";

import * as Effect from "effect/Effect";
import * as Either from "effect/Either";

import { SwarmieClient } from "./http-client";
import type { RequestError } from "./request-error";
import { requestUrl, userFixture } from "./test-helpers";

type InvalidResponseCase = {
  name: string;
  request: (client: SwarmieClient) => Effect.Effect<unknown, RequestError>;
  body: unknown;
};

const invalidResponses: InvalidResponseCase[] = [
  {
    name: "session identity",
    request: (client) => client.me(),
    body: { user: {}, csrf_token: "fixture" },
  },
  {
    name: "session CSRF",
    request: (client) => client.me(),
    body: { user: userFixture, csrf_token: "" },
  },
  {
    name: "workspace",
    request: (client) => client.workspace("workspace"),
    body: { id: "workspace" },
  },
  { name: "workspace list", request: (client) => client.workspaces(), body: [{ id: "workspace" }] },
  {
    name: "membership",
    request: (client) => client.members("workspace"),
    body: [{ role: "administrator" }],
  },
  {
    name: "invitation",
    request: (client) => client.invitations("workspace"),
    body: [{ email: "private@example.test" }],
  },
  {
    name: "passkey",
    request: (client) => client.passkeys(),
    body: [{ id: "key", name: "Device" }],
  },
  {
    name: "authentication result",
    request: (client) => client.signInWithPassword("member@example.test", "fixture"),
    body: { status: "unknown" },
  },
  {
    name: "verification challenge",
    request: (client) => client.signUpWithPassword("member@example.test", "fixture"),
    body: { status: "email_verification_required", challenge: "" },
  },
  {
    name: "WebAuthn options",
    request: (client) => client.passkeySignInOptions("member@example.test"),
    body: { challenge: "fixture", public_key: { challenge: 42 } },
  },
];

test.each(invalidResponses)(
  "rejects malformed $name without retaining response data or retrying",
  async ({ request, body }) => {
    let calls = 0;
    const client = new SwarmieClient({
      fetch: async () => {
        calls += 1;
        return Response.json(body);
      },
    });
    const result = await Effect.runPromise(Effect.either(request(client)));
    expect(Either.isLeft(result)).toBe(true);
    if (Either.isRight(result)) {
      throw new Error("Malformed response was accepted");
    }
    expect(result.left.reason).toBe("invalid-response");
    expect(JSON.stringify(result.left)).not.toContain("private@example.test");
    expect(calls).toBe(1);
  },
);

test("rejects an empty success for a response-bearing operation", async () => {
  const client = new SwarmieClient({ fetch: async () => new Response(null, { status: 204 }) });
  const result = await Effect.runPromise(Effect.either(client.me()));
  expect(Either.isLeft(result)).toBe(true);
  if (Either.isRight(result)) {
    throw new Error("Empty response was accepted");
  }
  expect(result.left.reason).toBe("invalid-response");
});

test("preserves optional WebAuthn request options and nested extensions", async () => {
  const options = {
    challenge: "fixture-continuation",
    public_key: {
      challenge: "Zml4dHVyZQ",
      rpId: "swarmie.test",
      timeout: 60_000,
      userVerification: "required",
      hints: ["client-device"],
      allowCredentials: [{ id: "a2V5", type: "public-key", transports: ["internal", "hybrid"] }],
      extensions: {
        appid: "https://swarmie.test",
        credProps: true,
        largeBlob: { read: true },
        prf: {
          eval: { first: "Zmlyc3Q", second: "c2Vjb25k" },
          evalByCredential: { a2V5: { first: "Zmlyc3Q" } },
        },
      },
    },
  };
  const client = new SwarmieClient({ fetch: async () => Response.json(options) });
  const result = await Effect.runPromise(client.passkeySignInOptions("member@example.test"));
  expect(result).toEqual(options);
});

