"""Refuse changed dependency projections before consumers resolve their exports."""

import importlib.util
from pathlib import Path
import tempfile
import unittest


SPEC = importlib.util.spec_from_file_location("tembra_tooling", Path(__file__).with_name("tooling.py"))
tooling = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(tooling)


class ProjectionIntegrityTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.original_sdk = tooling.SDK
        tooling.SDK = Path(self.directory.name)
        upstream = tooling.SDK / "upstream"
        upstream.mkdir()
        (upstream / "index.js").write_text("export const value = 1;\n")
        self.package = {"name": "@tembra/sdk", "private": True}
        tooling.write_json(tooling.SDK / "package.json", self.package)
        tooling.write_json(tooling.SDK / "provenance.json", {
            "source": tooling.SOURCE, "revision": tooling.REVISION,
            "files": tooling.inventory(upstream), "package": self.package})

    def tearDown(self):
        tooling.SDK = self.original_sdk
        self.directory.cleanup()

    def test_modified_generated_bytes_are_refused(self):
        (tooling.SDK / "upstream/index.js").write_text("export const value = 2;\n")
        with self.assertRaisesRegex(RuntimeError, "recorded generated bytes"):
            tooling.verify_sdk()

    def test_additional_generated_module_is_refused(self):
        (tooling.SDK / "upstream/unrecorded.js").write_text("export {};\n")
        with self.assertRaisesRegex(RuntimeError, "recorded generated bytes"):
            tooling.verify_sdk()

    def test_changed_dependency_or_export_is_refused(self):
        tooling.write_json(tooling.SDK / "package.json", {**self.package, "exports": "./foreign.js"})
        with self.assertRaisesRegex(RuntimeError, "exports or dependencies"):
            tooling.verify_sdk()

    def test_matching_projection_is_accepted(self):
        tooling.verify_sdk()


if __name__ == "__main__":
    unittest.main()
